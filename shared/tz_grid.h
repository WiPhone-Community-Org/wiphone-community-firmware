/*
 * tz_grid.h - which time zone a MEASURED position is in, and that zone's UTC offset at any
 * instant. It is the lookup half of "the clock follows the owner across zones". It does not
 * set anything; the caller decides.
 *
 * WHY. The phone's clock offset is a fixed number typed in Settings, with no DST rules.
 * Carried across a zone line, the phone keeps the old zone's time, and the Almanac's
 * sunrise, sunset and legal light come out hours off. The position fed in here must be
 * MEASURED: the woods plate's GPS, or the hotspot phone's GPS (self_pos.h). It must never be
 * an IP guess, a Wi-Fi guess or a bench fix. The owner's rule is that a wrong answer is worse than none. So this module
 * answers a zone only where it cannot be wrong at the grid's resolution. Otherwise it says
 * TZ_BORDER or TZ_NOT_COVERED, and the caller changes nothing.
 *
 * THE GRID (WiPhone/tz_grid_data.h, generated by tools/gen_tz_grid.py from
 * timezone-boundary-builder, which is derived from OpenStreetMap and is ODbL 1.0; see
 * THIRD-PARTY-NOTICES.md). Cells are 0.05 deg over lat 7..72 N, lon 172 E..50 W: North
 * America with Alaska and all of the Aleutians, Hawaii, Canada, Mexico, Central America and
 * the Caribbean basin.
 *   * A zone is answered only in a cell where neither the cell nor any of its 8 neighbours
 *     has a place where the CLOCK changes. That includes the coast of the territorial waters,
 *     and any cell with a zone whose rules are not modelled. So an answered point is at
 *     least one whole cell (5.6 km N-S; 5.5 km at 7 N down to 1.7 km at 72 N E-W) from any
 *     change of clock.
 *   * Lines between zones that keep the SAME clock are not borders: Detroit/Windsor, the
 *     Indiana counties that are all Eastern, Oregon's Mountain corner and Idaho. Within one
 *     cell of such a line the IANA name may be the neighbour's. The clock is identical by
 *     construction.
 *   * Only zones verified against tzdata over 2026..2035 as a standard offset plus NO DST or
 *     the US/CANADA rule are answered (TZ_RULE_NONE / TZ_RULE_USCAN). Cuba (DST at midnight)
 *     and Greenland (EU rule) are TZ_RULE_UNKNOWN: the lookup answers TZ_NOT_COVERED there,
 *     with why = TZ_WHY_UNKNOWN_RULE.
 *   * sinceUtc: tzdata 2026d moved BC (America/Vancouver, UTC-7) and Alberta and western NWT
 *     (America/Edmonton, America/Inuvik, UTC-6) to one offset all year from 2026-03-08. Each
 *     is modelled from that instant on, and an offset for an EARLIER instant is refused
 *     (TZ_NO_OFFSET): it was not verified.
 *
 * THE US/CANADA RULE is computed from first principles, with no time library. DST runs
 * from the 2nd Sunday of March at 02:00 local standard time to the 1st Sunday of November
 * at 02:00 local daylight time (01:00 standard). This is the 2007+ rule. It is applied to
 * any year; it was verified for 2026..2035.
 *
 * Pure: no Arduino/ESP-IDF headers, no heap, no static mutable state, no logging, C++11.
 * The grid is const data in flash: 81.5 KB once linked (65.4 KB runs, 5.2 KB row index,
 * 3.4 KB zone table, ~2.8 KB strings and attribution, ~2 KB code; xtensa gcc 5.2, -Os). A
 * lookup walks one row's runs: at most 48 today, and the test fails above 64.
 * tests/test_tzgrid.cpp proves it against tests/vectors_tzgrid.h. Those offsets come from
 * zoneinfo, not from this code; the lookups come from the generator's own grid. COVEY's
 * covey_ui/tzgrid.py is the same module in Python and is tested against the same vectors.
 */
#ifndef TZ_GRID_H
#define TZ_GRID_H

#include <stddef.h>
#include <stdint.h>

// tzGridLookup's answers below 0 (>= 0 is a zone index)
#define TZ_BORDER       (-1)    // within one cell of a change of clock: change nothing
#define TZ_NOT_COVERED  (-2)    // at sea, outside the grid, bad input, or rules not modelled

#define TZ_NO_OFFSET    (-32768)  // tzUtcOffsetMinutes: no answer

enum TzRule : uint8_t {
  TZ_RULE_NONE = 0,       // the standard offset all year
  TZ_RULE_USCAN = 1,      // + 60 min from the 2nd Sunday of March to the 1st Sunday of November
  TZ_RULE_UNKNOWN = 2,    // neither: never answered
};

// Why tzGridLookup answered what it did (a status line can say which "not set" it is)
enum TzWhy : uint8_t {
  TZ_WHY_ZONE = 0,          // answered a zone
  TZ_WHY_BORDER = 1,        // TZ_BORDER
  TZ_WHY_WATER = 2,         // TZ_NOT_COVERED: open sea, beyond any zone's territorial waters
  TZ_WHY_OUTSIDE = 3,       // TZ_NOT_COVERED: outside the grid (south of 7 N, north of 72 N, ...)
  TZ_WHY_UNKNOWN_RULE = 4,  // TZ_NOT_COVERED: in a zone whose rules are not modelled (Cuba, Greenland)
  TZ_WHY_BAD_INPUT = 5,     // TZ_NOT_COVERED: |lat| > 90 deg or |lon| > 180 deg
};

struct TzZone {
  const char* display;    // "Eastern", "Central, no DST", "Newfoundland"; the city for UNKNOWN (<= 16 chars)
  const char* iana;       // "America/New_York"
  const char* abbrStd;    // tzdata's abbreviation: "EST", "-03"
  const char* abbrDst;    // "EDT"; "" without DST
  int16_t stdMinutes;     // standard offset, minutes EAST of UTC (-300 = UTC-5)
  uint8_t rule;           // TzRule
  int64_t sinceUtc;       // 0, or the instant the rule took over: earlier instants are refused
};

struct TzGridInfo {
  const char* release;      // timezone-boundary-builder release, e.g. "2026d"
  const char* tzdata;       // the tzdata the rules were verified against
  const char* sha256;       // content hash (hex), the same in COVEY's tzgrid.bin
  const char* attribution;  // the ODbL / OpenStreetMap notice; show it wherever the data is credited
  int validFrom, validTo;   // the years the rules were verified for (inclusive)
  int32_t lat0E7, lon0E7, resE7;
  uint16_t rows, cols, zones;
  uint32_t runs;
};

/* The zone at a position in 1e-7 degrees (north and east positive; the mesh_pos/self_pos
 * units). A longitude at or east of 172 E is read as lon - 360, so 180 E == 180 W.
 * Returns the zone index (>= 0, see tzGridZone), TZ_BORDER or TZ_NOT_COVERED.
 * why (may be NULL) says which. */
int tzGridLookup(int32_t latE7, int32_t lonE7, uint8_t* why);

int tzGridZoneCount();
const TzZone* tzGridZone(int zone);           // NULL out of range
int tzGridFindZone(const char* iana);         // index, or -1 (NULL or not in the table)
const TzGridInfo* tzGridInfo();
const char* tzWhyText(uint8_t why);           // "near a zone boundary", "at sea", ...

/* True when two zones keep the same clock from both of their sinceUtc on: same standard offset
 * and same modelled rule. False for an UNKNOWN zone or a bad index. Moving between two zones
 * that keep the same clock changes nothing the owner can see. */
bool tzGridSameClock(int a, int b);

/* The zone's UTC offset in minutes at utcSeconds (UNIX time). TZ_NO_OFFSET for a bad index,
 * an UNKNOWN rule, an instant before the zone's sinceUtc, or |utcSeconds| >= 2^40. */
int tzUtcOffsetMinutes(int zone, int64_t utcSeconds);

/* The first instant STRICTLY after utcSeconds at which the zone's offset changes, with the
 * offset from then in *offsetAfter (may be NULL). 0 = none: no DST, UNKNOWN, a bad index,
 * before sinceUtc, or out of range. */
int64_t tzNextTransition(int zone, int64_t utcSeconds, int* offsetAfter);

/* The same two from a standard offset and a rule alone (no grid, no sinceUtc). A caller can
 * keep (stdMinutes, rule) in its settings and compute offsets without a lookup.
 * stdMinutes must be within +-24 h, else TZ_NO_OFFSET / 0. */
int tzRuleOffsetMinutes(int stdMinutes, uint8_t rule, int64_t utcSeconds);
int64_t tzRuleNextTransition(int stdMinutes, uint8_t rule, int64_t utcSeconds, int* offsetAfter);

/* The US/Canada rule's instants for one year, as UTC seconds: DST starts at 02:00 local
 * standard on the 2nd Sunday of March and ends at 02:00 local daylight on the 1st Sunday of
 * November. The start instant is the first second of daylight time; the end instant is the
 * first second of standard time. */
int64_t tzUsCanDstStart(int year, int stdMinutes);
int64_t tzUsCanDstEnd(int year, int stdMinutes);

#endif // TZ_GRID_H
