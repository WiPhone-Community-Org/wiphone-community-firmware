#!/usr/bin/env python3
import argparse
import json
import re
from pathlib import Path


def macro_name(value):
    return re.sub(r"[^A-Za-z0-9]+", "_", value).strip("_").upper()


def scan(root, kind):
    entries = []
    base = root / kind
    if not base.exists():
        return entries
    for manifest in sorted(base.glob("*/manifest.json")):
        try:
            data = json.loads(manifest.read_text())
        except json.JSONDecodeError as exc:
            raise SystemExit(f"Invalid JSON in {manifest}: {exc}")
        data["_manifest_dir"] = str(manifest.parent)
        entries.append(data)
    return entries


def validate_manifests(entries, kind, root):
    seen = set()
    required = {"id", "title"}
    if kind == "apps":
        required.add("implementation")
        required.add("factory")
    if kind == "settings":
        required.add("storageKey")
        required.add("type")

    for entry in entries:
        manifest_id = entry.get("id")
        manifest_dir = Path(entry["_manifest_dir"])
        if not manifest_id:
            raise SystemExit(f"Missing id in {manifest_dir / 'manifest.json'}")
        if manifest_id in seen:
            raise SystemExit(f"Duplicate {kind[:-1]} id: {manifest_id}")
        seen.add(manifest_id)
        missing = sorted(required - set(entry))
        if kind == "settings" and entry.get("registered"):
            missing = sorted((required | {"implementation", "load", "save"}) - set(entry))
        if kind == "apps" and entry.get("registered"):
            if "menuId" in entry:
                if not isinstance(entry["menuId"], int) or isinstance(entry["menuId"], bool):
                    raise SystemExit(
                        f"Invalid menuId for app {manifest_id} in "
                        f"{manifest_dir / 'manifest.json'}"
                    )
        if missing:
            raise SystemExit(
                f"Missing fields {', '.join(missing)} in "
                f"{manifest_dir / 'manifest.json'}"
            )
        if kind == "apps":
            implementation = root / entry["implementation"]
            if not implementation.exists():
                raise SystemExit(
                    f"App {manifest_id} implementation does not exist: {implementation}"
                )
        if kind == "settings" and entry.get("registered"):
            implementation = root / entry["implementation"]
            if not implementation.exists():
                raise SystemExit(
                    f"Setting {manifest_id} implementation does not exist: {implementation}"
                )


def esc(value):
    return json.dumps(str(value), ensure_ascii=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--profile", required=True)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    profile_file = args.root / "profiles" / f"{args.profile}.json"
    profile = json.loads(profile_file.read_text())
    enabled_apps = set(profile.get("apps", []))
    enabled_settings = set(profile.get("settings", []))

    all_apps = scan(args.root, "apps")
    all_settings = scan(args.root, "settings")
    validate_manifests(all_apps, "apps", args.root)
    validate_manifests(all_settings, "settings", args.root)

    known_apps = {entry["id"] for entry in all_apps}
    known_settings = {entry["id"] for entry in all_settings}
    unknown_apps = sorted(enabled_apps - known_apps)
    unknown_settings = sorted(enabled_settings - known_settings)
    if unknown_apps:
        raise SystemExit(f"Unknown app ids in {profile_file}: {', '.join(unknown_apps)}")
    if unknown_settings:
        raise SystemExit(
            f"Unknown setting ids in {profile_file}: {', '.join(unknown_settings)}"
        )

    apps = [
        entry for entry in all_apps
        if entry["id"] in enabled_apps
    ]
    settings = [
        entry for entry in all_settings
        if entry["id"] in enabled_settings
    ]

    app_ids = [entry["id"] for entry in apps]
    setting_ids = [entry["id"] for entry in settings]
    if len(app_ids) != len(set(app_ids)):
        raise SystemExit("Duplicate app id in profile")
    if len(setting_ids) != len(set(setting_ids)):
        raise SystemExit("Duplicate setting id in profile")

    lines = [
        "// Generated by tools/generate_extension_registry.py. Do not edit.",
        "#pragma once",
        '#include "ExtensionRegistry.h"',
        "",
    ]
    for entry in apps:
        if entry.get("registered"):
            lines.append(f'void* {entry["factory"]}(void* context);')
    for entry in settings:
        if entry.get("registered"):
            lines.append(f'void {entry["load"]}(void* context);')
            lines.append(f'void {entry["save"]}(void* context);')
    lines.append("")
    lines.append("namespace wiphone_generated {")
    for entry in apps:
        lines.append(f'#define WIPHONE_APP_{macro_name(entry["id"])} 1')
    for entry in settings:
        lines.append(f'#define WIPHONE_SETTING_{macro_name(entry["id"])} 1')
    if profile["name"] == "core":
        lines.append("#define WIPHONE_BUILD_CORE 1")
    else:
        lines.append("#define WIPHONE_BUILD_FULL 1")

    lines.append("")
    if apps:
        lines.extend(["static const wiphone::AppRegistration kAppRegistrations[] = {"])
        for entry in apps:
            factory = entry["factory"] if entry.get("registered") else "NULL"
            lines.append(
                "  {" + ", ".join([
                    esc(entry["id"]),
                    esc(entry["title"]),
                    esc(entry.get("group", "tools")),
                    factory,
                ]) + "},"
            )
        lines.extend(["};", "static const size_t kAppRegistrationCount = sizeof(kAppRegistrations) / sizeof(kAppRegistrations[0]);"])
        menu_apps = [entry for entry in apps if "menuId" in entry]
        lines.append("")
        if menu_apps:
            lines.extend(["static const wiphone::AppMenuRegistration kAppMenuRegistrations[] = {"])
            for entry in menu_apps:
                lines.append(
                    "  {" + ", ".join([
                        esc(entry["id"]),
                        esc(entry["title"]),
                        esc(entry.get("parent", entry.get("group", "tools"))),
                        str(entry["menuId"]),
                    ]) + "},"
                )
            lines.extend([
                "};",
                "static const size_t kAppMenuRegistrationCount = sizeof(kAppMenuRegistrations) / sizeof(kAppMenuRegistrations[0]);",
            ])
        else:
            lines.extend([
                "static const wiphone::AppMenuRegistration* kAppMenuRegistrations = NULL;",
                "static const size_t kAppMenuRegistrationCount = 0;",
            ])
    else:
        lines.extend([
            "static const wiphone::AppRegistration* kAppRegistrations = NULL;",
            "static const size_t kAppRegistrationCount = 0;",
            "",
            "static const wiphone::AppMenuRegistration* kAppMenuRegistrations = NULL;",
            "static const size_t kAppMenuRegistrationCount = 0;",
        ])

    lines.append("")
    if settings:
        lines.extend(["static const wiphone::SettingRegistration kSettingRegistrations[] = {"])
        for entry in settings:
            setting_type = entry.get("type", "Toggle")
            valid_types = {
                "Toggle": "wiphone::SettingType::Toggle",
                "Integer": "wiphone::SettingType::Integer",
                "String": "wiphone::SettingType::String",
                "Enumeration": "wiphone::SettingType::Enumeration",
            }
            if setting_type not in valid_types:
                raise SystemExit(f"Unsupported setting type: {setting_type}")
            lines.append(
                "  {" + ", ".join([
                    esc(entry["id"]),
                    esc(entry["title"]),
                    esc(entry.get("owner", "core")),
                    esc(entry.get("storageKey", entry["id"])),
                    valid_types[setting_type],
                    entry["load"] if entry.get("registered") else "NULL",
                    entry["save"] if entry.get("registered") else "NULL",
                ]) + "},"
            )
        lines.extend(["};", "static const size_t kSettingRegistrationCount = sizeof(kSettingRegistrations) / sizeof(kSettingRegistrations[0]);"])
    else:
        lines.extend([
            "static const wiphone::SettingRegistration* kSettingRegistrations = NULL;",
            "static const size_t kSettingRegistrationCount = 0;",
        ])
    lines.extend(["}", ""])

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
